/**
 * 这份数据怎么来的（要改密度/数量时按这个重跑）：
 *
 * ```python
 * import random
 * random.seed(20260823)          # 固定种子：必须可复现，否则每次改动 diff 全变
 * def min_d(x): return 15.0 - (15.0 - 5.5) * (x / 100.0)   # 左疏右密
 * x = 100.0 * (random.random() ** 0.62)                    # 采样偏向右侧
 * y = random.uniform(9, 91)
 * # 拒绝采样：与本层保持 min_d、与其它层保持 min_d * 0.72
 * # 右侧（x > 55）的星从更大更亮的档位里挑
 * ```
 *
 * 每层 45 / 45 / 31 颗，合计 121。按 x 五等分实测 13 / 14 / 19 / 28 / 47，
 * 严格单调递增。
 */

/** 把一层星星拼成 background-image。每颗一条 gradient，位置任意。 */
export function starsToBackground(layer: readonly (readonly [number, number, number, number])[]) {
  return layer
    .map(
      ([x, y, r, a]) =>
        `radial-gradient(circle ${r}px at ${x}% ${y}%, rgba(255,255,255,${a}) 0 62%, transparent 100%)`,
    )
    .join(", ");
}
