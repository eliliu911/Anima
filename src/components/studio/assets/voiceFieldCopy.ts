/**
 * 角色「配音音色」那一栏的措辞。
 *
 * # 为什么单独一份、还带测试
 *
 * 2026-09-18 用户看到下拉框里写着「跟全局设置（Edge 朗读（云端））」，问：
 *
 * > 「音色跟全局设置是什么意思？没办法不选？那不是会一直用音色？」
 *
 * 他的担心是**不成立**的 —— `character.voice_id` 全仓库只有一处读
 * （`cinema_dub.rs`），而配音只有组装页那个按钮会触发。不点配音，
 * 这一栏没有任何作用，片子用的是 H3 自己生成的原声。
 *
 * **但措辞让他以为它是常开的。** 两处毛病：
 *
 * 1. 「跟全局设置」听起来像「此刻正在用全局那把嗓子」，
 *    而实际是「**万一**你配音了才用」；
 * 2. 栏目名只写「音色」，没说是**配音**的音色 ——
 *    而这个项目里「音色」还指 H3 提示词里的中文音色描述，是另一回事。
 *
 * 所以这三句话要被测试钉住：栏目名带「配音」、空选项不说「跟全局设置」、
 * 说明里**第一句**就交代「不配音就用不到」。
 */

/** 栏目名。**必须带「配音」** —— 光写「音色」会和 H3 提示词里的音色描述混。 */
export const VOICE_FIELD_LABEL = "配音音色";

/**
 * 说明。**第一句就得是「不配音用不到」** ——
 * 用户的担心正是「是不是一直在用」，答案要排在最前面。
 */
export const VOICE_FIELD_HINT =
  "只有在组装页点了「配音」才用得到 —— 不配音的话这一栏没有任何作用，" +
  "片子用的是 H3 自己生成的原声（那条路的口型是对得上的）。" +
  "配音时：留空就用设置里的全局音色，指定了就用这个角色自己的嗓子。";

/**
 * 「没指定」那个选项怎么写。
 *
 * **不要写「跟全局设置」** —— 那听起来像此刻正在生效。
 * 引擎名单独放在后面，不嵌套括号（「跟全局设置（Edge 朗读（云端））」
 * 那种两层括号本身就难读）。
 */
export function unsetOptionLabel(engine: string): string {
  const e = engine.trim();
  return e ? `不指定 · 配音时用全局音色（${e}）` : "不指定 · 配音时用全局音色";
}

/**
 * 「这些音色是哪来的、想换别的去哪换」。
 *
 * # 为什么必须有这句
 *
 * 2026-09-18 用户：「我只看到了一个引擎，另外两个引擎没有在列表里。
 * EDGE 里的音色都是比较刻板的，另外几个为什么没添加呢」——
 * **六个引擎其实都在配置里**，音色列表只是跟着**当前选中的那个**走。
 * 他选的是 Edge（中文 14 个，固定），而 F5-TTS 当时就跑着、
 * 手里有 40 个音色（还带 angry / happy / sad 变体），他完全不知道。
 *
 * 下拉框里写个引擎名是不够的 —— 那读起来像「音色就这些」，
 * 而不是「这是**这个引擎**的，换个引擎就换一批」。
 *
 * # 顺带要说的耦合
 *
 * `tts_engine` 是**全局一个**：语音助手和短剧配音共用。换引擎会一起变。
 * 不说的话，用户为了配音换成 F5-TTS，然后发现跟 Anima 说话的嗓子也变了。
 */
export function engineSourceNote(engine: string, voiceCount: number): string {
  const e = engine.trim() || "当前引擎";
  const n = voiceCount > 0 ? `这 ${voiceCount} 个音色来自${e}` : `${e}没有可列的音色`;
  return (
    `${n}。**换个引擎就是另一批** —— 在「设置 → 语音」里换（本地克隆那几个音色最多）。` +
    `注意引擎是全局一个：语音助手和配音共用，换了两边都变。`
  );
}
