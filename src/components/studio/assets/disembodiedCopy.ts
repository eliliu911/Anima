/**
 * 「只有声音，没有身体」那个开关的措辞与联动。
 *
 * # 为什么单独一份、还带测试
 *
 * 2026-09-18 用户反馈：「这个出镜选项很 confuse，这个角色有可能出镜、
 * 有可能旁白，你说你是勾选还不勾选？没意义啊。」
 *
 * 功能本身是对的 —— 它管的是**永远拍不出来**（旁白员、电话那头的人、
 * 纯语音 AI），不是「这一次是旁白」。后者是逐句的事，由
 * `DialogueLine.off_screen` 管，分镜生成时自动标。
 *
 * 但原来的说明只写了「旁白、电话那头的人、纯语音 AI」——
 * **「旁白」正好是最容易两边都沾的那个词**，于是读起来像个逐次的选择。
 *
 * 所以这两句话要被测试钉住：说明里必须同时出现「永远」这层意思，
 * 和「偶尔旁白不要勾」这条反例。少任何一半，那个歧义就回来了。
 */

/** 勾选项的主标题。**必须带「从不」** —— 这是和逐句画外音的唯一区别。 */
export const DISEMBODIED_LABEL = "这个角色从不出镜（只有声音，没有身体）";

/** 说明。 */
export const DISEMBODIED_HINT =
  "旁白员、电话那头的人、纯语音 AI、一团没有轮廓的光 —— 这类角色根本拍不出来。" +
  "勾上等于说「他没有身体」：不给他出图，分镜也不单独给他镜头，台词压在对手戏角色的画面上。" +
  "偶尔来一段旁白的角色不要勾 —— 那是逐句的事，分镜会自己把那几句标成画外音。";

/**
 * 出图那一整套界面（构图模板、生成配置、生成按钮）要不要显示。
 *
 * **勾了「没有身体」就不该再问怎么画他的身体。** 原来是照常显示的，
 * 于是勾选框正压在三张构图模板卡上面，读起来像「在同一组设置里二选一」
 * —— 用户就是这么读的。
 */
export function showImageUi(kind: string, disembodied: boolean): boolean {
  return kind !== "character" || !disembodied;
}

/** 勾上之后顶替出图界面的那句话。**要说明怎么退回去**，不能只是消失。 */
export const DISEMBODIED_NOTE =
  "这个角色没有身体，所以不出图。取消上面的勾选就能回到出图界面。";
