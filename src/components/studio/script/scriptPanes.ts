import type { Group } from "./ScriptTree";

/**
 * 剧本编辑器左右两栏的取舍。
 *
 * # 原来的毛病：两栏是两套互不相干的数据
 *
 * 左边是剧本库自己的树，右边是**视频项目**里的分集（跨项目平铺）。
 * 点左边一份稿子，**整页被编辑器替换掉，树直接消失** ——
 * 因为渲染是 `document ? <编辑器> : <两栏>`，
 * 「选中」和「两栏并存」在结构上就是互斥的。
 *
 * 用户看到的是两个同名的「余波」：左边那个是剧本库里的文档，
 * 右边那个是视频项目里的分集。同名不同物，界面上看不出来。
 *
 * # 改成什么
 *
 * **左 = 故事（剧本项目），右 = 这个故事的分集。** 编辑器搬进右栏，
 * 树不消失。这和当初做剧本编辑器的初衷（资源管理器）本来就是一致的。
 *
 * # 为什么不把两套项目合并
 *
 * 用户早先明确要求过：「当前还不想在工作区创建视频项目，
 * **但是可以先把剧本编辑处理好**」。合并之后剧本项目就必须对应一个
 * 视频剧集了，那条要求直接作废。所以剧本库保留自己的项目，
 * 视频分集降级成右栏底下一个单独的区。
 */

/**
 * 右栏该显示哪个故事。
 *
 * # `undefined` 和 `null` 不是一回事
 *
 * `undefined` = **还没选过**（刚打开这一页），落到第一个故事；
 * `null` = 明确选了**未归档**那一组。
 *
 * 这两个一开始被我合成了一个 `null`，结果刚进页面默认停在「未归档」上 ——
 * 而未归档往往是最空的那一组，用户看到的第一眼是「我的稿子呢」。
 * 一个值两个意思，实跑第一眼就撞出来了。
 *
 * **选中的项目没了就回落到第一个**，而不是显示空白 ——
 * 空白会让人以为稿子丢了。项目可以被别处删掉（或者换台机器读旧配置），
 * 「不该发生」的事真发生时，后果不能是「东西人间蒸发」。
 */
/**
 * 左栏选中的是什么。
 *
 * **不要再用一个可空 id 表示三种状态。** 之前 `null` 同时表示
 * 「未归档」和「还没选」，刚进页面默认停在最空的那一组 ——
 * 一个值两个意思，实跑第一眼就撞出来了。现在第三种（视频分集）来了，
 * 更不能继续叠。
 */
export type Pane =
  /** 一个剧本项目。`id` 为 `null` 时是「未归档」那一组。 */
  | { kind: "story"; id: string | null }
  /**
   * 视频项目里的分集。
   *
   * **它不是某个剧本项目的子内容** —— 原来把它挂在每个项目页面底下，
   * 于是打开「余波」也能看到「米小团」的分集。而两者之间**没有任何
   * 链接字段**（`sendToProject` 建了副本但没记来源），所以挂在哪个
   * 项目下都是假的。它是另一类东西，给它自己的位置。
   */
  | { kind: "video" };

export function activeGroup(groups: Group[], selected: string | null | undefined): Group | null {
  if (!groups.length) return null;
  // `undefined` 不用单独判：`g.id ?? null` 永远是 string 或 null，
  // 对不上就落到下面那个 `?? groups[0]`。
  // （一开始这儿有一行 `if (selected === undefined) return groups[0]`，
  // 变异测试发现删掉它行为一模一样 —— **看着起作用实际不起作用的代码
  // 比没有更糟**，会让人以为这里的行为是它保证的。）
  return groups.find((g) => (g.id ?? null) === selected) ?? groups[0];
}
